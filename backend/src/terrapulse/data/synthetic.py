"""Deterministic SYNTHETIC dataset generator.

!!! Everything produced here is fabricated test data for exercising the ML
!!! pipeline and the UI. It is NOT derived from any satellite observation,
!!! inventory, or measurement of the 2024 Thame GLOF or any other real event.

The generator follows the canonical schema in :mod:`terrapulse.schema` and
documents every modelling assumption in ``SYNTHETIC_ASSUMPTIONS`` (also
written next to the CSV as ``*.card.json``).
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from terrapulse import schema
from terrapulse.config import RANDOM_SEED, SYNTHETIC_CSV

SYNTHETIC_ASSUMPTIONS = {
    "provenance": "SYNTHETIC - generated by terrapulse.data.synthetic; not real observations.",
    "purpose": "Exercise preprocessing, grouped validation, imbalance handling, reporting and UI.",
    "structure": [
        "N event groups (default 8), each a spatial cluster of samples around a random centre "
        "inside an approximate Solukhumbu bounding box. Event IDs are SYN-EVT-xx and do not "
        "correspond to real events.",
        "Events are assigned whole to train or test (train_test_group) so splits are by group.",
    ],
    "terrain": [
        "Elevation ~ event base (3000-4800 m) + N(0, 450 m); slope ~ N(28, 11) deg clipped to 0-75.",
        "TWI decreases with slope; distances to river/road are log-normal.",
    ],
    "environment": [
        "Rainfall is cumulative by construction (1d <= 3d <= 7d <= 30d) with an event-level storm intensity.",
        "Soil moisture increases with 7-day rainfall; NDVI decreases with elevation.",
        "Land cover is derived from elevation and NDVI; geology is sampled with elevation-dependent weights.",
    ],
    "label_mechanism": [
        "Latent susceptibility logit = slope bump (peak ~35 deg) + rainfall + soil moisture "
        "- NDVI - log distance to river + geology effect - curvature + event random effect + noise.",
        "Intercept is solved numerically so the expected positive rate is ~9% (class imbalance).",
        "~2% of labels are flipped, preferentially where label_confidence is low (label noise).",
    ],
    "sar_signal": [
        "Post-event SAR features are generated CONDITIONAL on the label to emulate a detectable "
        "change signal: positives get larger |backscatter difference|, lower coherence, and "
        "larger negative LOS displacement. This is a modelling assumption, not a physical result.",
        "C-band-like rows carry VV/VH only (HH/HV missing); L-band-like rows carry HH/HV only.",
    ],
    "missingness": {
        "hh/hv or vv/vh": "structurally missing by sensor polarization",
        "sar_coherence": "~10% (no suitable interferometric pair)",
        "los_displacement_mm": "~15% + extra where coherence < 0.25 (unwrapping failure)",
        "ndvi": "~12% (cloud cover)",
        "soil_moisture": "~7% (coarse product gaps)",
        "rainfall_30d_mm": "~3%",
        "distance_to_road_m": "~2%",
        "DEM void": "~1% of rows lose elevation/slope/aspect/curvature/twi together",
        "land_cover": "~1%",
    },
    "target_derived": "Severity, area, displacement and change_classification are derived from the "
                      "label AFTER sampling; they are post-event quantities and must never be predictors.",
}


@dataclass
class SyntheticConfig:
    n_events: int = 8
    samples_per_event: tuple[int, int] = (320, 520)
    n_test_events: int = 2
    target_positive_rate: float = 0.09
    seed: int = RANDOM_SEED


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def _solve_intercept(z: np.ndarray, rate: float) -> float:
    lo, hi = -20.0, 20.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if _sigmoid(z + mid).mean() > rate:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


def generate_synthetic_dataset(cfg: SyntheticConfig | None = None) -> pd.DataFrame:
    cfg = cfg or SyntheticConfig()
    rng = np.random.default_rng(cfg.seed)

    sizes = rng.integers(cfg.samples_per_event[0], cfg.samples_per_event[1], size=cfg.n_events)
    n = int(sizes.sum())
    event_idx = np.repeat(np.arange(cfg.n_events), sizes)
    event_ids = np.array([f"SYN-EVT-{i + 1:02d}" for i in range(cfg.n_events)])

    # --- event-level properties ------------------------------------------
    ev_lat = rng.uniform(27.6, 28.0, cfg.n_events)
    ev_lon = rng.uniform(86.5, 87.0, cfg.n_events)
    ev_base_elev = rng.uniform(3000, 4800, cfg.n_events)
    ev_storm = rng.uniform(20, 110, cfg.n_events)          # mean 1-day rainfall
    ev_effect = rng.normal(0, 0.45, cfg.n_events)          # unobserved event random effect
    ev_date = pd.to_datetime("2019-06-15") + pd.to_timedelta(
        rng.integers(0, 365 * 5, cfg.n_events), unit="D")

    # --- metadata ----------------------------------------------------------
    lat = ev_lat[event_idx] + rng.normal(0, 0.012, n)
    lon = ev_lon[event_idx] + rng.normal(0, 0.012, n)
    lband = rng.random(n) < 0.25
    mission = np.where(lband, "L-band-like (SYNTHETIC)", "C-band-like (SYNTHETIC)")
    polarization = np.where(lband, "HH+HV", "VV+VH")
    product_type = np.where(rng.random(n) < 0.7, "GRD", "SLC")
    orbit = np.where(rng.random(n) < 0.5, "ascending", "descending")

    # --- terrain -------------------------------------------------------------
    elevation = np.clip(ev_base_elev[event_idx] + rng.normal(0, 450, n), 1200, 6800)
    slope = np.clip(rng.normal(28, 11, n), 0, 75)
    aspect = rng.uniform(0, 360, n)
    curvature = rng.normal(0, 4, n)
    twi = np.clip(4 + 8 * np.exp(-slope / 15) + rng.normal(0, 1.2, n), 0.5, 25)
    dist_river = np.clip(rng.lognormal(np.log(600), 0.9, n), 5, 20000)
    dist_road = np.clip(rng.lognormal(np.log(3000), 1.0, n), 10, 60000)

    # --- environment -------------------------------------------------------
    r1 = rng.gamma(2.0, ev_storm[event_idx] / 2.0)
    r3 = r1 + rng.gamma(2.0, ev_storm[event_idx] / 2.5)
    r7 = r3 + rng.gamma(2.0, ev_storm[event_idx] / 2.0)
    r30 = r7 + rng.gamma(3.0, ev_storm[event_idx])
    soil = np.clip(0.12 + 0.0009 * r7 + rng.normal(0, 0.05, n), 0.02, 0.6)
    ndvi = np.clip(0.65 - (elevation - 3000) / 3500 + rng.normal(0, 0.1, n), -0.1, 0.88)

    land_cover = np.select(
        [elevation > 5200, ndvi < 0.12, (ndvi > 0.5) & (elevation < 3800),
         (elevation < 3200) & (rng.random(n) < 0.15), ndvi > 0.3],
        ["glacier_snow", "bare_rock", "forest", "cropland", "shrubland"],
        default="grassland",
    ).astype(object)
    land_cover[rng.random(n) < 0.01] = "settlement"
    geo_names = np.array(["gneiss", "schist", "granite", "quartzite", "moraine_deposit", "colluvium", "alluvium"])
    high = elevation > 4300
    p_high = np.array([0.25, 0.15, 0.15, 0.05, 0.25, 0.12, 0.03])
    p_low = np.array([0.28, 0.25, 0.10, 0.10, 0.05, 0.12, 0.10])
    geology = np.where(high, rng.choice(geo_names, n, p=p_high), rng.choice(geo_names, n, p=p_low))
    geo_effect = pd.Series(geology).map({"gneiss": 0.0, "schist": 0.3, "granite": -0.4, "quartzite": -0.2,
                                         "moraine_deposit": 0.9, "colluvium": 0.6, "alluvium": 0.2}).to_numpy()

    # --- label -------------------------------------------------------------
    z = (1.6 * np.exp(-((slope - 35) / 12) ** 2)
         + 0.9 * (r3 - r3.mean()) / r3.std()
         + 4.0 * (soil - 0.3)
         - 1.5 * (ndvi - 0.3)
         - 0.7 * np.log10(dist_river / 500)
         + geo_effect
         - 0.06 * curvature
         + ev_effect[event_idx]
         + rng.normal(0, 0.6, n))
    b0 = _solve_intercept(z, cfg.target_positive_rate)
    p = _sigmoid(z + b0)
    label = (rng.random(n) < p).astype(int)

    label_conf = np.clip(rng.beta(8, 2, n), 0.3, 1.0)
    flip = rng.random(n) < 0.02 * (1.6 - label_conf) / 0.6
    label = np.where(flip, 1 - label, label)

    # --- post-event SAR (label-conditional; detection signal) -------------
    inc = np.clip(38 + rng.normal(0, 6, n), 20, 48)
    vv_pre = -11 - 0.15 * (inc - 35) + 3.0 * ndvi + rng.normal(0, 1.5, n)
    sign = np.where(rng.random(n) < 0.6, 1.0, -1.0)
    bdiff = np.where(label == 1, sign * np.abs(rng.normal(3.0, 1.6, n)), rng.normal(0, 1.2, n))
    copol_post = vv_pre + bdiff
    crosspol_post = copol_post - 6.5 + rng.normal(0, 1.2, n)
    coh = np.clip(rng.normal(0.62 - 0.35 * ndvi, 0.12, n) - 0.18 * label, 0.02, 0.98)
    los = np.where(label == 1, rng.normal(-120, 90, n), rng.normal(0, 15, n))

    vv = np.where(lband, np.nan, copol_post)
    vh = np.where(lband, np.nan, crosspol_post)
    hh = np.where(lband, copol_post + rng.normal(1.0, 0.8, n), np.nan)
    hv = np.where(lband, crosspol_post + rng.normal(1.0, 0.8, n), np.nan)

    # --- target-derived -----------------------------------------------------
    area = np.where(label == 1, rng.lognormal(np.log(8000), 1.1, n), 0.0)
    disp = np.where(label == 1, rng.lognormal(np.log(15), 0.9, n), 0.0)
    q1, q2 = (np.quantile(area[label == 1], [0.4, 0.8]) if label.sum() else (0, 0))
    severity = np.where(label == 0, "none", np.where(area < q1, "low", np.where(area < q2, "moderate", "high")))
    u = rng.random(n)
    pos_change = np.where(dist_river < 300,
                          np.where(u < 0.5, "flood_scour", "debris_flow_deposit"),
                          np.where(u < 0.75, "landslide", "debris_flow_deposit"))
    pos_change = np.where((elevation > 4800) & (u > 0.92), "lake_drainage", pos_change)
    neg_change = np.where(rng.random(n) < 0.03, "vegetation_loss", "no_change")
    change = np.where(label == 1, pos_change, neg_change)

    df = pd.DataFrame({
        "vv_backscatter_db": vv, "vh_backscatter_db": vh, "hh_backscatter_db": hh, "hv_backscatter_db": hv,
        "sar_coherence": coh, "backscatter_difference_db": bdiff, "incidence_angle_deg": inc,
        "los_displacement_mm": los,
        "acquisition_date": (ev_date[event_idx] + pd.to_timedelta(rng.integers(1, 13, n), unit="D")).strftime("%Y-%m-%d"),
        "orbit_direction": orbit, "polarization": polarization,
        "elevation_m": elevation, "slope_deg": slope, "aspect_deg": aspect, "curvature": curvature, "twi": twi,
        "distance_to_river_m": dist_river, "distance_to_road_m": dist_road,
        "rainfall_1d_mm": r1, "rainfall_3d_mm": r3, "rainfall_7d_mm": r7, "rainfall_30d_mm": r30,
        "soil_moisture": soil, "ndvi": ndvi, "land_cover": land_cover, "geology": geology,
        "landslide_label": label, "landslide_severity": severity, "landslide_area_m2": area,
        "landslide_displacement_m": disp, "change_classification": change,
        "sample_id": [f"SYN-{i:06d}" for i in range(1, n + 1)],
        "event_id": event_ids[event_idx], "latitude": lat, "longitude": lon,
        "event_date": ev_date[event_idx].strftime("%Y-%m-%d"),
        "satellite_mission": mission, "product_type": product_type,
        "inventory_source": np.where(rng.random(n) < 0.5, "synthetic_inventory_A", "synthetic_inventory_B"),
        "label_confidence": label_conf,
    })

    # --- missingness -----------------------------------------------------------
    def drop(col, frac, extra_mask=None):
        m = rng.random(n) < frac
        if extra_mask is not None:
            m |= extra_mask
        df.loc[m, col] = np.nan

    drop("sar_coherence", 0.10)
    drop("los_displacement_mm", 0.15, (df["sar_coherence"] < 0.25) & (rng.random(n) < 0.6))
    drop("ndvi", 0.12)
    drop("soil_moisture", 0.07)
    drop("rainfall_30d_mm", 0.03)
    drop("distance_to_road_m", 0.02)
    void = rng.random(n) < 0.01
    df.loc[void, ["elevation_m", "slope_deg", "aspect_deg", "curvature", "twi"]] = np.nan
    df.loc[rng.random(n) < 0.01, "land_cover"] = np.nan

    n_missing_sar = df[["sar_coherence", "los_displacement_mm"]].isna().sum(axis=1)
    df["data_quality_flag"] = np.where(
        (n_missing_sar == 2) | void, "poor",
        np.where((n_missing_sar == 1) | (df["sar_coherence"] < 0.3), "fair", "good"))

    # --- group split: whole events go to test ------------------------------
    pos_by_event = df.groupby("event_id")["landslide_label"].sum()
    candidates = [e for e in event_ids if pos_by_event[e] >= 5]
    test_events = list(rng.choice(candidates, size=cfg.n_test_events, replace=False))
    df["train_test_group"] = np.where(df["event_id"].isin(test_events), "test", "train")

    df[schema.PROVENANCE_COLUMN] = "SYNTHETIC"
    return df[schema.ALL_COLUMN_NAMES + [schema.PROVENANCE_COLUMN]]


def write_synthetic_dataset(path: Path = SYNTHETIC_CSV, cfg: SyntheticConfig | None = None) -> Path:
    cfg = cfg or SyntheticConfig()
    df = generate_synthetic_dataset(cfg)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False, float_format="%.5g")
    card = {
        "file": path.name,
        "rows": len(df),
        "columns": len(df.columns),
        "seed": cfg.seed,
        "config": {"n_events": cfg.n_events, "samples_per_event": list(cfg.samples_per_event),
                   "n_test_events": cfg.n_test_events, "target_positive_rate": cfg.target_positive_rate},
        "positive_rate": float(df["landslide_label"].mean()),
        "test_events": sorted(df.loc[df["train_test_group"] == "test", "event_id"].unique().tolist()),
        "assumptions": SYNTHETIC_ASSUMPTIONS,
    }
    path.with_suffix(".card.json").write_text(json.dumps(card, indent=2))
    return path
